// Private, expiring recipient snapshots. Credentials stay in Vercel, never in Lasso.
import { createHash, timingSafeEqual } from 'node:crypto';

const TOKEN = /^[A-Za-z0-9_-]{32}$/; // 192 random bits, generated by Lasso's CSPRNG.
const OWNER = /^[A-Za-z0-9_-]{43}$/; // Separate 256-bit management capability.
const ASSET = /^(?:|source|slide|(?:excerpt|download)(?:\?as=(?:pdf|docx|jpeg))?)$/;
const MAX_BODY = 4_000_000; // Below Vercel's 4.5 MB request and response limit.
const LIFETIME = 48 * 3600_000;
const hash = value => createHash('sha256').update(value).digest('hex');
const keyFor = token => `lasso:share:${hash(token)}`;
const HEADERS = {
  'cache-control': 'private, no-store, max-age=0',
  'cdn-cache-control': 'no-store',
  'vercel-cdn-cache-control': 'no-store',
  'referrer-policy': 'no-referrer',
  'x-content-type-options': 'nosniff',
  'x-robots-tag': 'noindex, nofollow, noarchive',
  // Even a modified client cannot publish active content on the marketing origin.
  'content-security-policy': "sandbox allow-same-origin allow-downloads; default-src 'none'; style-src 'unsafe-inline'; img-src 'self' data:; frame-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'self'",
};
const json = (status, value) => new Response(JSON.stringify(value), { status, headers: { ...HEADERS, 'content-type': 'application/json' } });
const unavailable = status => new Response('<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Share unavailable · Lasso</title><body><h1>This share is unavailable</h1><p>The link is invalid, expired, or has been revoked. Ask the sender for a new link.</p></body></html>', {
  status, headers: { ...HEADERS, 'content-type': 'text/html; charset=utf-8' },
});

export function redis(env = process.env, fetchImpl = fetch) {
  const url = env.KV_REST_API_URL || env.UPSTASH_REDIS_REST_URL;
  const token = env.KV_REST_API_TOKEN || env.UPSTASH_REDIS_REST_TOKEN;
  if (!url || !token) return null;
  return async commands => {
    const response = await fetchImpl(`${url.replace(/\/$/, '')}/pipeline`, {
      method: 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' },
      body: JSON.stringify(commands), signal: AbortSignal.timeout(12_000), redirect: 'error',
    });
    if (!response.ok) throw new Error('Share storage unavailable.');
    const result = await response.json();
    if (!Array.isArray(result) || result.length !== commands.length || result.some(entry => entry.error)) throw new Error('Share storage unavailable.');
    return result.map(entry => entry.result);
  };
}

async function readBody(request) {
  if (Number(request.headers.get('content-length')) > MAX_BODY) throw { status: 413 };
  if (!request.body) throw { status: 400 };
  const reader = request.body.getReader();
  const chunks = [];
  let size = 0;
  try {
    while (true) {
      const { value, done } = await reader.read();
      if (done) break;
      size += value.length;
      if (size > MAX_BODY) { await reader.cancel(); throw { status: 413 }; }
      chunks.push(Buffer.from(value));
    }
    return JSON.parse(Buffer.concat(chunks).toString('utf8'));
  } catch (error) { throw { status: error.status || 400 }; }
  finally { reader.releaseLock(); }
}

function validate(body, now) {
  if (!body || typeof body.token !== 'string' || !TOKEN.test(body.token) || typeof body.expiresAt !== 'string') return false;
  const expires = Date.parse(body.expiresAt);
  if (!Number.isFinite(expires) || expires <= now || expires > now + LIFETIME) return false;
  if (!Array.isArray(body.assets) || body.assets.length < 1 || body.assets.length > 12) return false;
  const paths = new Set();
  for (const asset of body.assets) {
    if (!asset || typeof asset.path !== 'string' || !ASSET.test(asset.path) || paths.has(asset.path)) return false;
    paths.add(asset.path);
    if (typeof asset.body !== 'string' || !asset.body || Buffer.from(asset.body, 'base64').toString('base64') !== asset.body) return false;
    if (typeof asset.contentType !== 'string' || asset.contentType.length > 150 || /[\r\n]/.test(asset.contentType)) return false;
    if (asset.path === '' && asset.contentType !== 'text/html; charset=utf-8') return false;
    if (asset.path === 'source' && asset.contentType !== 'application/pdf') return false;
    if (asset.path === 'slide' && asset.contentType !== 'image/jpeg') return false;
    if (asset.path.startsWith('download') || asset.path.startsWith('excerpt')) {
      if (typeof asset.disposition !== 'string' || !asset.disposition.startsWith('attachment;') || asset.disposition.length > 1000 || /[\r\n]/.test(asset.disposition)) return false;
    }
  }
  return paths.has('');
}

function ownerKey(request) {
  const value = request.headers.get('authorization')?.replace(/^Bearer /, '');
  return OWNER.test(value ?? '') ? hash(value) : null;
}
const sameHash = (a, b) => typeof a === 'string' && typeof b === 'string' && a.length === 64 && b.length === 64
  && timingSafeEqual(Buffer.from(a), Buffer.from(b));

// Keep an expiring tombstone so a delayed upload cannot bring a revoked URL back.
const REVOKE = `local value = redis.call('GET', KEYS[1])
if not value then return 0 end
local record = cjson.decode(value)
if record.owner ~= ARGV[1] then return -1 end
record.assets = nil
record.revoked = true
redis.call('SET', KEYS[1], cjson.encode(record), 'KEEPTTL')
return 1`;

export function createShareHandlers({ run = redis(), now = Date.now } = {}) {
  async function rateLimit(request) {
    // Vercel overwrites x-vercel-forwarded-for; do not trust client forwarding headers.
    const ip = request.headers.get('x-vercel-forwarded-for')?.split(',')[0].trim() || 'unknown';
    const hour = Math.floor(now() / 3600_000);
    const local = `lasso:share:rate:${hour}:${hash(ip)}`;
    const global = `lasso:share:rate:${hour}:all`;
    const [hits, , total] = await run([
      ['INCR', local], ['EXPIRE', local, 3600, 'NX'], ['INCR', global], ['EXPIRE', global, 3600, 'NX'],
    ]);
    return hits <= 30 && total <= 1000;
  }
  return {
    async POST(request) {
      if (request.headers.has('origin')) return json(403, { error: 'Desktop uploads only.' });
      if (!/^application\/json(?:;|$)/i.test(request.headers.get('content-type') || '')) return json(415, { error: 'Send JSON.' });
      const owner = ownerKey(request);
      if (!owner) return json(401, { error: 'A management key is required.' });
      if (!run) return json(503, { error: 'Hosted sharing is not configured.' });
      try {
        if (!await rateLimit(request)) return json(429, { error: 'Too many shares. Try again later.' });
        const body = await readBody(request);
        if (!validate(body, now())) return json(400, { error: 'Invalid share snapshot.' });
        // Store only protocol fields, never additional client data or credentials.
        const assets = body.assets.map(({ path, contentType, disposition, body }) => ({ path, contentType, disposition, body }));
        const digest = hash(JSON.stringify({ expiresAt: body.expiresAt, assets }));
        const value = { owner, digest, expiresAt: body.expiresAt, assets };
        const key = keyFor(body.token);
        const ttl = Math.max(1, Math.ceil((Date.parse(body.expiresAt) - now()) / 1000));
        const [saved] = await run([['SET', key, JSON.stringify(value), 'EX', ttl, 'NX']]);
        if (!saved) {
          const [existing] = await run([['GET', key]]);
          const previous = existing && JSON.parse(existing);
          if (!previous || previous.revoked || !sameHash(previous.owner, owner) || previous.digest !== digest) return json(409, { error: 'Share already exists.' });
        }
        return json(201, { token: body.token, expiresAt: body.expiresAt });
      } catch (error) {
        return json(error.status || 502, { error: error.status === 413 ? 'This share is too large to host (about 3 MB including its preview and downloads).' : 'The share could not be published.' });
      }
    },
    async DELETE(request) {
      if (request.headers.has('origin')) return json(403, { error: 'Desktop requests only.' });
      const token = new URL(request.url).searchParams.get('token');
      const owner = ownerKey(request);
      if (!owner) return json(401, { error: 'A management key is required.' });
      if (!TOKEN.test(token ?? '')) return json(404, { error: 'Share not found.' });
      if (!run) return json(503, { error: 'Hosted sharing is not configured.' });
      try {
        const [result] = await run([['EVAL', REVOKE, 1, keyFor(token), owner]]);
        if (result === -1) return json(404, { error: 'Share not found.' });
        // Already expired/missing is successfully inaccessible too.
        return json(200, { revoked: true });
      } catch { return json(502, { error: 'The share could not be revoked. Try again.' }); }
    },
    async GET(request) {
      const url = new URL(request.url);
      const token = url.searchParams.get('token');
      const part = url.searchParams.get('asset') || '';
      const assetPath = part + (url.searchParams.has('as') ? `?as=${url.searchParams.get('as')}` : '');
      if (!TOKEN.test(token ?? '') || !ASSET.test(assetPath)) return unavailable(404);
      if (!run) return unavailable(503);
      try {
        const [stored] = await run([['GET', keyFor(token)]]);
        if (!stored) return unavailable(404);
        const record = JSON.parse(stored);
        if (record.revoked || Date.parse(record.expiresAt) <= now()) return unavailable(410);
        const asset = record.assets.find(entry => entry.path === assetPath);
        if (!asset) return unavailable(404);
        const headers = { ...HEADERS, 'content-type': asset.contentType };
        if (asset.path.startsWith('download') || asset.path.startsWith('excerpt')) {
          // User-supplied HTML, SVG and office files are always attachments.
          headers['content-type'] = 'application/octet-stream';
          headers['content-disposition'] = asset.disposition;
        }
        if (asset.path === '') headers['content-security-policy'] = HEADERS['content-security-policy'].replace("frame-ancestors 'self'", "frame-ancestors 'none'");
        return new Response(Buffer.from(asset.body, 'base64'), { headers });
      } catch { return unavailable(502); }
    },
  };
}
