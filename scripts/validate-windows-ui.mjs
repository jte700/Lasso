// Isolated UI regression: real engine + temporary project; no personal workspace data.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { spawn } from 'node:child_process';
import { createApplication } from '../src/server.js';
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'lasso-windows-ui-'));
const output = path.resolve(process.argv[2] ?? 'docs/validation/windows-2026-10-17');
await fs.mkdir(output, { recursive:true });
await fs.mkdir(path.join(root, 'Research', 'Finance'), { recursive:true });
await fs.writeFile(path.join(root, 'Research', 'Finance', 'Costs.csv'), 'Account,Current period,Prior period\nOffice supplies,400,384\nTravel,1250,1100\nEquipment,3200,2800\n');
await fs.writeFile(path.join(root, 'Research', 'Project brief.md'), '# Project brief\n\nOffice supplies cost 400 this period.\n\nTravel costs increased from the prior period.\n');
await fs.writeFile(path.join(root, 'Research', 'Research notes.md'), '# Research notes\n\nThe team reviewed the current period budget and supporting evidence.\n');
const app = createApplication({ dataDir:path.join(root,'data'), watchProjects:false });
const actor = {id:'human:ui-test',displayName:'Local user',actorType:'HUMAN_SELF'};
const { project } = app.timeline.importProject(path.join(root,'Research'),actor,{watch:false,name:'Research workspace'});
app.dependencies.ensureIndex(project.id);
await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const url = `http://127.0.0.1:${app.server.address().port}/?platform=windows`;
const chromePath = process.env.CHROME_PATH ?? (process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : process.platform === 'win32' ? path.join(process.env.PROGRAMFILES,'Google/Chrome/Application/chrome.exe') : 'google-chrome');
let chrome, socket;
const errors = [], checks = [];
const delay = ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function until(check,label,timeout=15000) { const end=Date.now()+timeout; while(Date.now()<end){ if(await check())return; await delay(100); } throw new Error(label); }
try {
  const profile=path.join(root,'chrome');
  chrome=spawn(chromePath,[`--user-data-dir=${profile}`,'--headless=new','--remote-debugging-port=0','--no-first-run','--no-default-browser-check','--disable-background-networking','--disable-component-update','--disable-sync','--window-size=1440,1000',url],{stdio:'ignore'});
  let port;
  await until(async()=>{try{port=Number((await fs.readFile(path.join(profile,'DevToolsActivePort'),'utf8')).split('\n')[0]);return port;}catch{return false;}},'Chrome startup');
  const pages=await (await fetch(`http://127.0.0.1:${port}/json`)).json();
  socket=new WebSocket(pages.find(p=>p.url.startsWith(url)).webSocketDebuggerUrl);
  await new Promise((resolve,reject)=>{socket.addEventListener('open',resolve,{once:true});socket.addEventListener('error',reject,{once:true});});
  let id=0;const pending=new Map();
  socket.addEventListener('message',event=>{const m=JSON.parse(event.data);if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails.exception?.description??m.params.exceptionDetails.text);const p=pending.get(m.id);if(p){pending.delete(m.id);clearTimeout(p.timer);m.error?p.reject(new Error(m.error.message)):p.resolve(m.result);}});
  const call=(method,params={})=>new Promise((resolve,reject)=>{const key=++id;const timer=setTimeout(()=>reject(new Error(`Timeout: ${method}`)),15000);pending.set(key,{resolve,reject,timer});socket.send(JSON.stringify({id:key,method,params}));});
  const evaluate=async expression=>{const r=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw new Error(r.exceptionDetails.exception?.description??r.exceptionDetails.text);return r.result.value;};
  const click=selector=>evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const screen=async name=>{const r=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});await fs.writeFile(path.join(output,name),Buffer.from(r.data,'base64'));};
  await call('Runtime.enable');
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:960,deviceScaleFactor:1,mobile:false});
  await until(()=>evaluate(`document.querySelectorAll('.wb-file').length===3`),'Indexed sources visible');
  assert.equal(await evaluate(`document.documentElement.dataset.platform`),'windows');
  assert.equal(await evaluate(`document.querySelector('#search-shortcut').textContent`),'Ctrl+K');
  assert.equal(await evaluate(`document.querySelector('#choose-folder').hidden`),true,'Web preview cannot invoke native dialogs');
  checks.push('Windows platform labels and browser capability separation');
  await click('#windows-settings');
  await evaluate(`document.querySelector('#windows-theme').value='alabaster';document.querySelector('#windows-theme').dispatchEvent(new Event('change'));document.querySelector('#settings-dialog').close()`);
  await screen('windows-library-light.png');
  await click('.wb-file[data-file="Finance/Costs.csv"]');
  await click('.wb-item[data-object]');
  await until(()=>evaluate(`!!document.querySelector('[data-share-source]')`),'Source selection actions');
  await screen('windows-evidence-light.png');
  await click('[data-share-source]');
  await until(()=>evaluate(`!!document.querySelector('[data-share-scope]')`),'Share composer');
  assert.equal(await evaluate(`document.querySelector('[data-share-scope]').value`),'INDEXED');
  assert.equal(app.objectShares.listShares(project.id).length,0,'Opening composer cannot mint a link');
  assert.equal(await evaluate(`document.querySelector('.source-dialog-preview').textContent.includes('[object Object]')`),false,'Source preview renders actual cell values');
  await evaluate(`document.querySelector('[data-share-scope]').value='REDACTED';document.querySelector('[data-share-scope]').dispatchEvent(new Event('change'))`);
  assert.equal(await evaluate(`document.querySelector('[data-create-share]').disabled`),true);
  await click('[data-mask="0:1:1"]');
  await screen('windows-share-redaction.png');
  await click('[data-create-share]');
  await until(()=>evaluate(`document.querySelector('[data-share-url]').value.length>0`),'Explicit share creation');
  const shared=app.objectShares.listShares(project.id)[0];
  assert.equal(shared.accessScope,'REDACTED');
  assert.equal(shared.redactions.length,1);
  const publicPage=await (await fetch(shared.url)).text();
  assert.ok(!publicPage.includes('<td>400</td>'),'Masked source value excluded from shared table');
  await click('[data-revoke-share]');
  await until(()=>Promise.resolve(!!app.objectShares.listShares(project.id)[0].revokedAt),'Share revoked');
  await click('.source-dialog [data-close-dialog]');
  checks.push('Pinned source preview; deliberate redaction sharing; revoked link');
  await click('#windows-settings');
  await evaluate(`document.querySelector('#windows-theme').value='carbon';document.querySelector('#windows-theme').dispatchEvent(new Event('change'));document.querySelector('#settings-dialog').close()`);
  await screen('windows-evidence-dark.png');
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.wb')).backgroundColor`),'rgb(39, 39, 39)');
  checks.push('Light and dark appearance with live theme switch');
  await click('[data-workspace-query="changes"]');
  await until(()=>evaluate(`document.querySelector('.wb-heading h1')?.textContent==='Recent changes'`),'Change history');
  await click('[data-workspace-query="share list"]');
  await until(()=>evaluate(`document.querySelector('.wb-heading h1')?.textContent==='Shared links'`),'Share history');
  await click('[data-workspace-query="conflicts"]');
  await until(()=>evaluate(`document.querySelector('.wb-heading h1')?.textContent==='Needs attention'`),'Source review');
  checks.push('Changes, shared links, and review navigation');
  await click('[data-tab="doc:Project brief.md"]');
  await until(()=>evaluate(`!!document.querySelector('#document-body')`),'Writing editor');
  await evaluate(`const block=document.querySelector('.manuscript-block:last-child');block.textContent+=' Verified on Windows preview.';block.dispatchEvent(new InputEvent('input',{bubbles:true,inputType:'insertText',data:' Verified on Windows preview.'}));`);
  await until(()=>evaluate(`!document.querySelector('#save-document').disabled`),'Editor dirty state');
  await click('#save-document');
  await until(async()=>(await fs.readFile(path.join(root,'Research','Project brief.md'),'utf8')).includes('Verified on Windows preview.'),'Real file saved');
  const navigationState = await evaluate(`({active:[...document.querySelectorAll('.rail-navigation .rail-item.active')].map(b=>b.textContent),classes:document.querySelector('#app-window').className,platform:window.lassoPlatform.name})`);
  assert.equal(navigationState.active.length,0,JSON.stringify(navigationState));
  await screen('windows-writing-dark.png');
  checks.push('Writing editor saves changes to the real temporary project file');
  await click('#project-pill');await click('#sidebar-add');
  assert.equal(await evaluate(`document.querySelector('[name="rootPath"]').placeholder`),'C:\\Users\\you\\Documents\\Research');
  await click('#import-dialog [data-close-dialog]');
  await call('Input.dispatchKeyEvent',{type:'keyDown',key:'k',code:'KeyK',modifiers:2});
  await call('Input.dispatchKeyEvent',{type:'keyUp',key:'k',code:'KeyK',modifiers:2});
  assert.equal(await evaluate(`document.activeElement.id`),'terminal-input');
  await call('Input.dispatchKeyEvent',{type:'keyDown',key:'P',code:'KeyP',modifiers:10});
  await call('Input.dispatchKeyEvent',{type:'keyUp',key:'P',code:'KeyP',modifiers:10});
  assert.equal(await evaluate(`document.querySelector('.cmd-palette').hidden`),false);
  checks.push('Windows folder path prompt, Ctrl+K search, and Ctrl+Shift+P palette');
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(output,'ui-results.json'),JSON.stringify({checks,errors,host:process.platform,nativeWindowsExecution:false},null,2));
  console.log(`Passed ${checks.length} UI workflows. Screenshots: ${output}`);
} finally {
  socket?.close();chrome?.kill();await app.close();
  await delay(300);await fs.rm(root,{recursive:true,force:true,maxRetries:5,retryDelay:200});
}
